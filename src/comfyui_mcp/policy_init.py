"""Suggest an enforce-mode allowlist from the audit log (issue #230).

Audit mode records ``nodes_used`` for every inspected workflow. This module
turns that history into a reviewable allowlist: observed node types with
counts and first/last seen, dangerous or policy-denied nodes excluded, and
stale allowlist entries flagged.

The CLI wrapper is ``scripts/policy_init.py``.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from comfyui_mcp.config import load_settings

_DEFAULT_AUDIT_FILE = Path("~/.comfyui-mcp/audit.log")
_DEFAULT_CONFIG_FILE = Path("~/.comfyui-mcp/config.yaml")


def _out(message: str = "") -> None:
    sys.stdout.write(message + "\n")


def _err(message: str) -> None:
    sys.stderr.write(message + "\n")


@dataclass
class NodeUsage:
    count: int = 0
    first_seen: str = ""
    last_seen: str = ""

    def record(self, timestamp: str) -> None:
        self.count += 1
        if timestamp:
            if not self.first_seen or timestamp < self.first_seen:
                self.first_seen = timestamp
            if not self.last_seen or timestamp > self.last_seen:
                self.last_seen = timestamp


@dataclass
class Suggestions:
    allowlist: dict[str, NodeUsage] = field(default_factory=dict)
    dangerous_seen: dict[str, NodeUsage] = field(default_factory=dict)
    never_seen: list[str] = field(default_factory=list)
    inspections: int = 0
    skipped_lines: int = 0


def collect_usage(audit_file: Path) -> tuple[dict[str, NodeUsage], int, int]:
    """Return (node usage, inspections, skipped malformed lines)."""
    usage: dict[str, NodeUsage] = {}
    inspections = 0
    skipped = 0

    with audit_file.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                skipped += 1
                continue
            if not isinstance(record, dict):
                skipped += 1
                continue
            nodes = record.get("nodes_used")
            if not isinstance(nodes, list) or not nodes:
                continue

            inspections += 1
            timestamp = str(record.get("timestamp") or "")
            for node_type in {node for node in nodes if isinstance(node, str) and node}:
                usage.setdefault(node_type, NodeUsage()).record(timestamp)

    return usage, inspections, skipped


def build_suggestions(
    usage: dict[str, NodeUsage],
    *,
    blocked_nodes: list[str],
    current_allowlist: list[str],
    min_count: int = 1,
) -> Suggestions:
    """Split observed nodes into suggested / dangerous / stale buckets."""
    blocked = set(blocked_nodes)
    suggestions = Suggestions()

    for node_type in sorted(usage):
        observed = usage[node_type]
        if observed.count < min_count:
            continue
        if node_type in blocked:
            suggestions.dangerous_seen[node_type] = observed
        else:
            suggestions.allowlist[node_type] = observed

    suggestions.never_seen = sorted(node for node in current_allowlist if node not in usage)
    return suggestions


def render_fragment(suggestions: Suggestions) -> str:
    """Render a copy-pasteable YAML fragment (comments are intentional)."""
    lines = [
        "# Generated by scripts/policy_init.py — review before enforcing.",
        "# Counts are inspected workflows; duplicate nodes in one graph count once.",
        "security:",
        "  allowed_nodes:",
    ]
    if not suggestions.allowlist:
        lines.append("    []")
    for node_type in sorted(suggestions.allowlist):
        observed = suggestions.allowlist[node_type]
        detail = f"{observed.count} inspection(s)"
        if observed.first_seen:
            detail += f", {observed.first_seen} .. {observed.last_seen}"
        lines.append(f"    - {json.dumps(node_type)}  # {detail}")
    return "\n".join(lines) + "\n"


def apply_to_config(config_path: Path, allowlist: list[str]) -> Path | None:
    """Merge the allowlist into the config, keeping a .bak of an existing file.

    YAML comments are lost on rewrite; returns the backup path, or ``None``
    when the config did not exist yet.
    """
    backup: Path | None = None
    data: dict[str, Any] = {}
    if config_path.exists():
        backup = config_path.with_suffix(config_path.suffix + ".bak")
        shutil.copy2(config_path, backup)
        loaded = yaml.safe_load(config_path.read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            data = loaded
    else:
        config_path.parent.mkdir(parents=True, exist_ok=True)

    security = data.setdefault("security", {})
    if not isinstance(security, dict):
        raise ValueError("security section is not a mapping in the config file")
    security["allowed_nodes"] = sorted(allowlist)

    config_path.write_text(
        yaml.safe_dump(data, sort_keys=False, default_flow_style=False),
        encoding="utf-8",
    )
    return backup


def _print_report(
    *,
    suggestions: Suggestions,
    audit_file: Path,
    config_path: Path,
    applied: bool,
) -> None:
    _out(f"Audit file: {audit_file}")
    _out(f"Inspected workflows: {suggestions.inspections}")
    if suggestions.skipped_lines:
        _out(f"Skipped malformed lines: {suggestions.skipped_lines}")
    _out(f"Suggested allowlist: {len(suggestions.allowlist)} node type(s)")

    if suggestions.dangerous_seen:
        _out("\nDangerous/policy-denied nodes seen (excluded from the allowlist):")
        for node_type, observed in sorted(suggestions.dangerous_seen.items()):
            _out(f"  - {node_type} ({observed.count} inspection(s))")

    if suggestions.never_seen:
        _out("\nCurrent allowlist entries never observed (review or remove):")
        for node_type in suggestions.never_seen:
            _out(f"  - {node_type}")

    _out()
    _out(render_fragment(suggestions).rstrip())
    if applied:
        _out(f"Updated {config_path} (backup: {config_path}.bak where it existed).")
        _out("Switch security.mode to 'enforce' to use it.")
    else:
        _out(f"Re-run with --apply to write the allowlist to {config_path}.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Suggest an enforce-mode allowlist from the ComfyUI MCP audit log."
    )
    parser.add_argument(
        "--audit-file",
        type=Path,
        default=_DEFAULT_AUDIT_FILE,
        help=f"Audit JSONL path (default: {_DEFAULT_AUDIT_FILE})",
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=_DEFAULT_CONFIG_FILE,
        help=f"Config path (default: {_DEFAULT_CONFIG_FILE})",
    )
    parser.add_argument(
        "--min-count",
        type=int,
        default=1,
        help="Only suggest nodes seen in at least this many workflows (default: 1)",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Write the allowlist into the config (keeps a .bak; drops YAML comments)",
    )
    args = parser.parse_args(argv)

    audit_file = args.audit_file.expanduser()
    config_path = args.config.expanduser()
    if not audit_file.exists() or not audit_file.is_file():
        _err(f"Audit log not found: {audit_file}")
        return 1

    usage, inspections, skipped = collect_usage(audit_file)
    settings = load_settings(config_path=config_path)
    blocked = set(settings.security.dangerous_nodes) | set(settings.security.policy.deny_nodes)
    suggestions = build_suggestions(
        usage,
        blocked_nodes=sorted(blocked),
        current_allowlist=settings.security.allowed_nodes,
        min_count=max(1, args.min_count),
    )
    suggestions.inspections = inspections
    suggestions.skipped_lines = skipped

    if inspections == 0:
        _err(f"No inspected workflows found in {audit_file}")
        return 1

    if args.apply:
        if not suggestions.allowlist:
            _err("Nothing to apply: the suggested allowlist is empty.")
            return 1
        backup = apply_to_config(config_path, sorted(suggestions.allowlist))
        _print_report(
            suggestions=suggestions,
            audit_file=audit_file,
            config_path=config_path,
            applied=True,
        )
        if backup is not None:
            _out(f"Old config copied to {backup}.")
    else:
        _print_report(
            suggestions=suggestions,
            audit_file=audit_file,
            config_path=config_path,
            applied=False,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
